// Plural forms (Intl.PluralRules categories).
const PLURALS = {
  cs: {
    rows: { one: '{n} řádek', few: '{n} řádky', many: '{n} řádku', other: '{n} řádků' },
    suppliers: { one: '{n} dodavatel', few: '{n} dodavatelé', many: '{n} dodavatele', other: '{n} dodavatelů' },
    warnings: { one: '{n} varování', few: '{n} varování', many: '{n} varování', other: '{n} varování' },
  },
  en: {
    rows: { one: '{n} line', other: '{n} lines' },
    suppliers: { one: '{n} supplier', other: '{n} suppliers' },
    warnings: { one: '{n} warning', other: '{n} warnings' },
  },
};

function fill(str, vars) {
  if (!vars) return str;
  return str.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined && vars[k] !== null ? String(vars[k]) : m));
}

export function translate(lang, key, vars) {
  const table = STRINGS[lang] || STRINGS.cs;
  const str = table[key] ?? STRINGS.cs[key] ?? key;
  return fill(str, vars);
}

const pluralRules = {};

export function plural(lang, key, n, formatted) {
  const l = PLURALS[lang] ? lang : 'cs';
  const forms = PLURALS[l][key];
  if (!forms) return String(n);
  let cat = 'other';
  try {
    pluralRules[l] ||= new Intl.PluralRules(LOCALES[l]);
    cat = pluralRules[l].select(n);
  } catch {
    cat = n === 1 ? 'one' : 'other';
  }
  const str = forms[cat] ?? forms.other;
  return fill(str, { n: formatted ?? n });
}
